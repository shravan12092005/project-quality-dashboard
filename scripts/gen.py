"""
gen.py  —  Synthetic data generator for Project Quality Dashboard
==================================================================
Generates three CSV files:
  data/raw/issues.csv   (~200 rows)
  data/raw/risks.csv    (~80 rows)
  data/raw/reviews.csv  (~120 rows)

ALL DATA GENERATED BY THIS SCRIPT IS SYNTHETIC.
It does not represent any real organisation, project, or person.
See NOTICE file for full disclosure.

Usage:
    python scripts/gen.py
    (Run from the project-quality-dashboard/ directory)

Random seed: 42  (fully reproducible)
"""

import csv
import random
from datetime import date, timedelta
from pathlib import Path

# ── Config ────────────────────────────────────────────────────────────────────
SEED = 42
random.seed(SEED)

BASE_DIR = Path(__file__).resolve().parent.parent
RAW_DIR = BASE_DIR / "data" / "raw"
RAW_DIR.mkdir(parents=True, exist_ok=True)

# Values must match those in Processed_QA_Defects.csv so dimension joins work
PROJECTS = ["A", "B", "C", "D", "E"]
MODULES = ["Application", "BIOS", "Driver", "FW", "Server Specific"]
PHASES = ["BST", "Integration 1", "Integration 2", "System Test", "Final Release"]
DATE_START = date(2023, 1, 1)
DATE_END = date(2023, 12, 31)


def rand_date(start: date = DATE_START, end: date = DATE_END) -> date:
    delta = (end - start).days
    return start + timedelta(days=random.randint(0, delta))


def fmt(d: date | None) -> str:
    return d.strftime("%d-%m-%Y") if d else ""


# ── issues.csv ────────────────────────────────────────────────────────────────
ISSUE_TYPES = ["Action Item", "Audit Finding", "Review Finding", "Defect"]
SEVERITIES = ["Critical", "High", "Medium", "Low"]
ISSUE_STATUSES = ["Open", "In Progress", "Closed", "Overdue"]
ROOT_CAUSES = [
    "Code Integration", "FW Integration", "OS-specific",
    "Change Request", "Driver", "Product Request", "Unclassified",
]
QUALITY_GATES = ["Design Review", "Code Review", "Integration Test", "System Test", "Final Release"]
OWNERS = [f"Engineer_{i:02d}" for i in range(1, 16)]

N_ISSUES = 200
issues_rows = []
for i in range(1, N_ISSUES + 1):
    created = rand_date()
    due = created + timedelta(days=random.randint(3, 45))
    status = random.choice(ISSUE_STATUSES)
    if status == "Closed":
        closed = created + timedelta(days=random.randint(1, (due - created).days + 10))
        closed = min(closed, DATE_END)
    else:
        closed = None
    issues_rows.append({
        "Issue_ID": f"ISS-{i:04d}",
        "Project": random.choice(PROJECTS),
        "Phase": random.choice(PHASES),
        "Module": random.choice(MODULES),
        "Type": random.choice(ISSUE_TYPES),
        "Severity": random.choice(SEVERITIES),
        "Status": status,
        "Owner": random.choice(OWNERS),
        "Root_Cause": random.choice(ROOT_CAUSES),
        "Quality_Gate": random.choice(QUALITY_GATES),
        "Created_Date": fmt(created),
        "Due_Date": fmt(due),
        "Closed_Date": fmt(closed),
    })

issues_path = RAW_DIR / "issues.csv"
with open(issues_path, "w", newline="", encoding="utf-8") as f:
    writer = csv.DictWriter(f, fieldnames=list(issues_rows[0].keys()))
    writer.writeheader()
    writer.writerows(issues_rows)
print(f"  ✓  issues.csv  — {len(issues_rows)} rows → {issues_path}")


# ── risks.csv ─────────────────────────────────────────────────────────────────
RISK_CATEGORIES = [
    "Technical", "Schedule", "Resource", "Quality", "Compliance", "External",
]
RISK_STATUSES = ["Open", "Mitigated", "Closed", "Escalated"]

N_RISKS = 80
risks_rows = []
for i in range(1, N_RISKS + 1):
    created = rand_date()
    review_date = created + timedelta(days=random.randint(7, 60))
    probability = random.randint(1, 5)
    impact = random.randint(1, 5)
    risk_score = probability * impact
    status = random.choice(RISK_STATUSES)
    risks_rows.append({
        "Risk_ID": f"RSK-{i:04d}",
        "Project": random.choice(PROJECTS),
        "Module": random.choice(MODULES),
        "Category": random.choice(RISK_CATEGORIES),
        "Probability": probability,
        "Impact": impact,
        "Risk_Score": risk_score,
        "Status": status,
        "Owner": random.choice(OWNERS),
        "Created_Date": fmt(created),
        "Review_Date": fmt(review_date),
        "Description": f"Synthetic risk {i} — {random.choice(RISK_CATEGORIES)} risk in {random.choice(MODULES)}",
    })

risks_path = RAW_DIR / "risks.csv"
with open(risks_path, "w", newline="", encoding="utf-8") as f:
    writer = csv.DictWriter(f, fieldnames=list(risks_rows[0].keys()))
    writer.writeheader()
    writer.writerows(risks_rows)
print(f"  ✓  risks.csv   — {len(risks_rows)} rows → {risks_path}")


# ── reviews.csv ───────────────────────────────────────────────────────────────
REVIEW_TYPES = ["Design Review", "Code Review", "Test Review", "Audit", "Process Review"]
REVIEW_STATUSES = ["Planned", "In Progress", "Completed", "Overdue"]

N_REVIEWS = 120
reviews_rows = []
for i in range(1, N_REVIEWS + 1):
    scheduled = rand_date()
    status = random.choice(REVIEW_STATUSES)
    if status == "Completed":
        completed = scheduled + timedelta(days=random.randint(0, 14))
        completed = min(completed, DATE_END)
    else:
        completed = None
    findings = random.randint(0, 12) if status in ("Completed", "In Progress") else 0
    reviews_rows.append({
        "Review_ID": f"REV-{i:04d}",
        "Project": random.choice(PROJECTS),
        "Module": random.choice(MODULES),
        "Review_Type": random.choice(REVIEW_TYPES),
        "Status": status,
        "Owner": random.choice(OWNERS),
        "Scheduled_Date": fmt(scheduled),
        "Completed_Date": fmt(completed),
        "Findings_Count": findings,
        "Phase": random.choice(PHASES),
    })

reviews_path = RAW_DIR / "reviews.csv"
with open(reviews_path, "w", newline="", encoding="utf-8") as f:
    writer = csv.DictWriter(f, fieldnames=list(reviews_rows[0].keys()))
    writer.writeheader()
    writer.writerows(reviews_rows)
print(f"  ✓  reviews.csv — {len(reviews_rows)} rows → {reviews_path}")

print("\nAll synthetic data written to data/raw/")
print("Reminder: This data is SYNTHETIC. See NOTICE for full disclosure.")
